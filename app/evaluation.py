from app.services.rag_service import retrieve_documents , query_documents
from langchain_groq import ChatGroq
import json
from app.config import settings



evaluator = ChatGroq(
    api_key= settings.GROQ_API_KEY,
    model_name ="openai/gpt-oss-20b",
    temperature= 0
)

evaluation_case =[
    {
        "question": " What is the 2024 top funding countries?",
        "expected_doc_id":"2",
        "reference_answer":"United States ,European ,Commission,United Kingdom,Switzerland , The Netherlands,Sweden ,Japan ,Germany,Norway ,Finland ,Others"
                                    
    },
    {
        "question" :"In  2025,  How many pourcent of the IFRC-DREFs and  Emergence y Appeals launched included cash and voucher assistance (CVA) elements?. ",
        "expected_doc_id":"1",
        "reference_answer":"54%"
    }
]

total_hits = 0
total_precision = 0
faithfulness_scores_list = []
correctness_scores = []

def evaluate_faithfulness(context , generated_answer):
    prompt = f"""
    You are a faithfulness evaluator.
    
    Evaluate the generated answer using ONLY the provided context.
    Identify every factual claim in the answer.
    Count how many claims are supported by the context.
    Do not use external knowledge.
    
    Context:
    {context}
    
    Generated Answer:
    {generated_answer}
    
    Return ONLY a valid JSON object in this exact format:
    {{
        "total_claims": 2,
        "supported_claims": 1,
        "unsupported_claims": 1
    }}

    The numbers above are examples, not the evaluation result.
    Do not include explanations or Markdown code fences.
    
    """
    
    result = evaluator.invoke(prompt)
    print("RAW EVALUATOR RESPONSE:", repr(result.content))
    
    try:
        return json.loads(result.content)
    
    except Exception as e:
        print(f"Faithfulness evaluation failed: {type(e).__name__}: {e}")
        raise


def evaluate_answer_correctness(generated_answer , reference_answer):
    prompt = f"""
    
    You are an answer correctness evaluator.
    
    compare the generated answer with the Trust reference answer.
    
    Evaluate factual meaning , not exact wording.
    Accept paraphrases that communicate the same facts.
    Do not use external knwoledge.
    
    Generated Answer:
    {generated_answer}
    
    Reference Answer:
    {reference_answer}
    
    Return ONLY valid JSON with these keys:
    "Correct": true or false
    "Reason":"brief explanation"
    
    """
    
    result = evaluator.invoke(prompt)
    
    return json.loads(result.content)

# Loop
for test_case in evaluation_case:
    question = test_case["question"]
    expected_doc_id = test_case["expected_doc_id"]
    reference_answer =test_case["reference_answer"]
    
    retrieved_chunks = retrieve_documents(question,org_id=1, k=5)
    
    response = query_documents(question ,org_id=1)
    
    generated_answer = response['answer'] #Response generated by groq LLM
    context = response['context']
    if expected_doc_id == "2":
        print("\nRETRIEVED CONTEXT:")
        print(context)
    
    
    retrieve_doc_ids = response['doc_ids']
    
    evaluation_result = evaluate_faithfulness(context, generated_answer)
    correctness_result = evaluate_answer_correctness (generated_answer , reference_answer)
    print("Generated Answer:", generated_answer)
    print("Reference Answer:", reference_answer)
    print("Correctness Evaluation:", correctness_result)
    correctness_score = 100 if correctness_result["Correct"] else 0
    correctness_scores.append(correctness_score)
    print(f"Answer Correctness: {correctness_score}%")
    
    print("TYPE:", type(evaluation_result))
    print("VALUE:", repr(evaluation_result))
    supported_claims = evaluation_result['supported_claims']
    total_claims = evaluation_result['total_claims']
    
    if total_claims > 0 :
        faithfulness_score =(supported_claims / total_claims) * 100
    else:
        faithfulness_score = None
    
    if faithfulness_score is not None:
        faithfulness_scores_list.append(faithfulness_score)
    
    
    print(f"Faithfulness Score: {faithfulness_score}%")
    
    retrieved_doc_ids = [
        doc.metadata.get("doc_id")
        for doc in retrieved_chunks
    ]
    
    if retrieved_doc_ids:
        
        precision = retrieved_doc_ids.count(expected_doc_id) / len(retrieved_doc_ids) * 100
         
    else:
        precision = 0
    
    total_precision += precision
    
    if expected_doc_id in retrieved_doc_ids:
        total_hits += 1
        print(f"Test passed for question: '{question}', doc_id:{expected_doc_id} found in retrieved doc_ids: {retrieved_doc_ids}")
    else:
        print(f"Test failed for question: '{question}'. Expected doc_id: '{expected_doc_id}', but got: {retrieved_doc_ids}")
        
    print(f"Precision :{precision}%")
    
    
    
    

if faithfulness_scores_list:
    mean_faithfulness = sum(faithfulness_scores_list) / len (faithfulness_scores_list)
else:
    mean_faithfulness = None
  
hit_rate = total_hits / len(evaluation_case) * 100
mean_precision = total_precision /len(evaluation_case)
mean_correctness = (sum(correctness_scores) / len(correctness_scores) if correctness_scores else None)

print(f"Total hits: {hit_rate}%")
print(f"Mean Precision@5: {mean_precision:.1f}%")
print(f'Mean Faithfulness: {mean_faithfulness}%')
print(f'Mean Correctness:{mean_correctness}')
